/**
 * 경로 요청에 싣는 사용자 좌표.
 *
 * 서버가 진입 노드를 다시 고르는 데 쓴다. `startNodeId`는 위치 인식 시점에 정해지는데 그때는
 * 목적지를 모르므로 거리만 보고 가장 가까운 노드를 고른다. 그것이 목적지 반대쪽이면 첫 안내가
 * 뒤로 걷는 구간이 된다 — 역삼역 B3에서 3번 출구로 갈 때 좌표 없이는 140.53m·131초,
 * 좌표를 함께 보내면 124.53m·118초다. (S15P11A206-337)
 */
export interface RouteOrigin {
  currentMapX: number;
  currentMapY: number;
}

/**
 * 좌표를 실제로 실어 보낼지. **켜져 있다.**
 *
 * 한동안 껐던 값이다. 서버가 진입 노드를 고를 때 후보를 "같은 층 + 목적지에서 도달 가능"으로만
 * 걸러서, 선로 건너편 승강장이 뽑혔다.
 *
 * ```
 * 내 위치      노드 209 (49.1, 24.3)
 * 계단 5(236)  (21.6, 27.4)  같은 승강장   직선 27.7m
 * 계단 7(241)  (21.8,  1.6)  선로 건너편   직선 35.6m   ← 이쪽이 뽑혔다
 * ```
 *
 * 두 승강장은 B3 간선만으로는 이어지지 않는데, 도달성 판정이 **전체 그래프** 기준이라 B2로
 * 올라갔다 내려오는 경로를 통해 이어진 것으로 계산됐다. 그래서 건너편이 후보에 남았고, 화면에는
 * 선로를 관통하는 선이 그려졌다.
 *
 * 서버가 두 가지로 막았다(S15P11A206-338). 후보를 **그 층 간선만으로 닿는 노드**로 좁히고,
 * 직선 구간에 15m 상한을 뒀다. 앞의 것이 선로 건너편을, 뒤의 것이 걸어갈 수 없는 지름길을
 * 막는다. 그래서 다시 켰다.
 *
 * 되돌릴 일이 생기면 이 값만 false로 두면 된다. 좌표가 없으면 서버가 요청에 온 `startNodeId`를
 * 그대로 쓰므로(`withChosenEntry`) 내가 서 있는 노드에서 경로가 시작한다 — 진입 노드 재선택
 * 이전 동작이다. (S15P11A206-337 · S15P11A206-338)
 */
export const SEND_CURRENT_POSITION = true;

/**
 * 조회 키에 싣는 자리수. 0.1m = 10cm.
 *
 * 좌표가 조금만 흔들려도 키가 달라지면 그때마다 경로를 다시 받는다. 10cm 차이로 진입 노드가
 * 바뀌는 경우는 없으니 그 아래는 같은 요청으로 본다.
 *
 * 요청 본문에도 **같은 반올림 값**을 싣는다. 키만 반올림하면 한 키에 여러 요청이 대응해,
 * 캐시가 돌려준 응답이 어느 좌표로 계산된 것인지 말할 수 없게 된다.
 */
const COORD_STEP = 10;

/**
 * 좌표를 요청에 실을 형태로 다듬는다. 실을 것이 없으면 null.
 *
 * **짝으로 있어야 한다.** 백엔드가 한쪽만 온 좌표를 무시하므로(`RouteCreateRequest`) 반쪽을
 * 보내는 것은 안 보내는 것과 같고, 화면만 보냈다고 믿게 된다.
 *
 * 좌표 정합이 없는 층(역삼역 B1)은 위치 인식이 좌표를 주지 못해 null이다. 그때는 서버가
 * 예전처럼 가장 가까운 노드로 시작한다 — 선택 필드이므로 조회 자체가 막히지는 않는다.
 */
export function routeOriginOf(
  mapX: number | null | undefined,
  mapY: number | null | undefined,
): RouteOrigin | null {
  if (!Number.isFinite(mapX) || !Number.isFinite(mapY)) return null;

  return {
    currentMapX: Math.round((mapX as number) * COORD_STEP) / COORD_STEP,
    currentMapY: Math.round((mapY as number) * COORD_STEP) / COORD_STEP,
  };
}
