-- V10. 역삼역 출구의 접근성 플래그 정정 (S15P11A206-207)
--
-- V8 재시드는 출구 9개의 is_accessible 을 모두 0 으로 넣었다. 다른 시설 유형은
-- 판단해서 채웠지만(엘리베이터 6개·개찰구 4개 = 1, 계단 31개·에스컬레이터 14개 = 0)
-- 출구만 일괄 0 이라 3·4번 출구가 실제와 다르다.
--
-- 판정 근거 — 계단·에스컬레이터를 제외한 간선(RouteType.ELEVATOR_ONLY 조건)만으로
-- 그래프를 순회하면 도달 가능한 출구는 B2 의 3번(node 153)·4번(node 150) 둘뿐이다.
-- B1↔B2 구간에 엘리베이터가 없어 B1 출구 7개(1·2·5·6·7·8번·GFC 연결통로)는 닿지 않는다.
-- S15P11A206-198 에서 재확인한 값이다.
--
-- 이 값은 장소-출구 추천에서 "엘리베이터로 갈 수 있는 최근접 출구"를 고르는 후보
-- 필터로 쓴다(S15P11A206-317 연계). 그래프에서 파생된 사실을 컬럼에 담는 것이므로,
-- 간선을 바꾸는 마이그레이션에서는 이 플래그도 함께 다시 봐야 한다.
--
-- linked_node_id 로 매칭한다. V8 이 facility_id 를 auto_increment 로 넣어 값이 고정이
-- 아닌 반면, 노드 ID 는 V8 에 명시돼 있어 안정적이다.
-- station_id = 1 은 V8 이 역삼역에 명시적으로 부여한 값이다.

UPDATE facility
SET is_accessible = 1,
    updated_at    = NOW(6)
WHERE station_id = 1
  AND facility_type = 'exit'
  AND linked_node_id IN (150, 153);
